// Keep all source inventory and stable draft IDs. The wider practice remains
// explicitly distinguished from the authored route in the internal audit.
export function sequenceChapterThree(draft) {
  const replaced = new Set([
    "a-c3l2-1",
    "a-c3l2-2",
    "a-c3l3-1",
    "a-c3l3-use",
    "a-c3-inviting-1",
  ]);
  const retiredLessons = draft.filter((l) => replaced.has(l.id));
  draft = draft.filter((l) => !replaced.has(l.id));
  const places = draft.filter((l) => l.sourceLesson === "c3l5");
  const route = chapterThreeRoute(places);
  const bySource = (key) => draft.filter((l) => l.sourceLesson === key);
  const order = [
    "c3l1",
    "c3-destination-contrast",
    "c3l2",
    "c3l6",
    "c3-days-parts",
    "c3-clock-hours",
    "c3l3",
    "c3-inviting",
    "c3l7",
    "c3-half-hours",
    "c3-day-periods",
    "c3-lex-public-transport",
    "c3l4",
    "c3-transport-endings",
    "c3-ordinals-early",
    "c3-lex-everyday-public-signs",
    "c3-ordinals-later",
    "c3-lex-landmarks",
    "c3-lex-errands-in-town",
    "c3-lex-directions-and-movement",
    "c3-lex-when-and-how-often",
  ];
  const expanded = order.flatMap((key) =>
    key === "c3-half-hours"
      ? [chapterThreeHalfHours(), ...bySource(key)]
      : bySource(key),
  );
  const used = new Set([...places, ...expanded]);
  // This prepared exchange is retained for saved-state compatibility and now
  // occurs after its replies, destinations and meeting patterns were introduced.
  return {
    lessons: [...route, ...expanded, ...draft.filter((l) => !used.has(l))],
    retiredLessons,
  };
}

